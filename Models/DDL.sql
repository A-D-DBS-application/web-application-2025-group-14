CREATE TABLE company (
  company_name text NOT NULL PRIMARY KEY
);

CREATE TABLE app_user (
  username text NOT NULL PRIMARY KEY,
  password text NOT NULL,
  company_name text NOT NULL,
  FOREIGN KEY (company_name) REFERENCES company (company_name)
    ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE material (
  material_id int GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  material_type text NOT NULL,
  description text NOT NULL,
  lifecycle text,
  brand text NOT NULL,
  price numeric,
  company_name  text NOT NULL,
  CONSTRAINT UC1 UNIQUE(company_name, material_type, description),
  FOREIGN KEY (company_name) REFERENCES company (company_name)
    ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE zone (
  zone_id int GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  zone_name char(3) NOT NULL,
  company_name text NOT NULL,
  CONSTRAINT UC2 UNIQUE (company_name, zone_name),
  FOREIGN KEY (company_name) REFERENCES company (company_name)
    ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE item (
  item_id int GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  material_id int NOT NULL,
  zone_id int NOT NULL,
  purpose text NOT NULL,
  packaging text NOT NULL,
  quantity int NOT NULL,
  comment text,
  CONSTRAINT UC3 UNIQUE(material_id, zone_id, purpose, packaging),
  CONSTRAINT CC2 CHECK(purpose IN('keep', 'sell', 'dispose')),
  CONSTRAINT CC3 CHECK(packaging IN('open', 'closed', 'none')),
  FOREIGN KEY (material_id) REFERENCES material (material_id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  FOREIGN KEY (zone_id) REFERENCES zone (zone_id)
    ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE reservation (
  item_id int NOT NULL,
  username text NOT NULL,
  date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  quantity int NOT NULL,
  project text,
  PRIMARY KEY (item_id, username, date),
  FOREIGN KEY (item_id) REFERENCES item (item_id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  FOREIGN KEY (username) REFERENCES app_user (username)
    ON DELETE CASCADE ON UPDATE CASCADE
);